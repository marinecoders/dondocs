import 'fake-indexeddb/auto';
import { afterEach, expect, it, vi } from 'vitest';
import { cleanup, render, screen, waitFor } from '@testing-library/react';
import userEvent from '@testing-library/user-event';
import { PackageAssemblyPanel } from '@/components/PackageAssemblyPanel';
import { createActionPackage, getPackageRevision, listActionPackages } from '@/lib/actionPackages';
import { resolveExportDeploymentPolicy } from '@/lib/exportDeploymentPolicy';
import * as classification from '@/config/classification';
vi.mock('@/stores/backupStore', () => ({ scheduleBackup: vi.fn() }));
afterEach(() => { cleanup(); vi.restoreAllMocks(); });
it('does not save reviewed assembly settings after a read-only transition during publication', async () => {
  const policy = resolveExportDeploymentPolicy({ hostname: 'localhost', environment: null, runtime: { status: 'absent' } });
  vi.spyOn(classification, 'getExportDeploymentPolicy').mockResolvedValue(policy);
  vi.spyOn(classification, 'getExportDeploymentPolicySync').mockReturnValue(policy);
  const record = await createActionPackage(`Assembly gate ${crypto.randomUUID()}`), user = userEvent.setup(), onApply = vi.fn();
  const props = { record, revision: getPackageRevision(record), disabled: false, busy: false, run: async (action: () => Promise<void>) => action(), signal: () => undefined, isCurrent: () => true, onApply };
  const view = render(<PackageAssemblyPanel {...props} />);
  await user.click(screen.getByRole('checkbox', { name: 'Include a package cover' }));
  await user.click(screen.getByRole('checkbox', { name: /^I reviewed the assembly profile/ }));
  let finish!: (value: typeof policy) => void;
  vi.mocked(classification.getExportDeploymentPolicy).mockImplementationOnce(() => new Promise(resolve => { finish = resolve; }));
  await user.click(screen.getByRole('button', { name: 'Save assembly settings' }));
  await waitFor(() => expect(finish).toBeTypeOf('function'));
  view.rerender(<PackageAssemblyPanel {...props} disabled />); finish(policy);
  await waitFor(() => expect(screen.getByRole('region', { name: 'Assembly layout' })).toHaveAttribute('aria-busy', 'false'));
  expect(onApply).not.toHaveBeenCalled();
  expect((await listActionPackages()).find(item => item.id === record.id)).toEqual(record);
  view.rerender(<PackageAssemblyPanel {...props} />);
  expect(screen.getByRole('checkbox', { name: /^I reviewed the assembly profile/ })).not.toBeChecked();
});
