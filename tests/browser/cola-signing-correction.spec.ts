import { expect, test } from '@playwright/test';
import { expandPackageTools, newPackage, openPackageWorkspace, packageSection } from './_helpers/packageWorkspace';

test('takes the applicant to the missing dependent row and returns to the same signature', async ({ page }) => {
  await page.addLocatorHandler(page.getByRole('button', { name: 'Download reviewed signing files' }), button => button.click());
  await page.goto('/');
  await page.getByRole('button', { name: 'Start writing' }).click();
  const workspace = await openPackageWorkspace(page);
  await newPackage(workspace);
  await expandPackageTools(workspace);
  await workspace.getByRole('button', { name: 'Start Okinawa overseas COLA', exact: true }).click();
  await workspace.getByRole('button', { name: 'Who is the claim for?', exact: true }).click();
  const intake = workspace.getByRole('region', { name: 'Action intake' });
  await intake.getByLabel('Member name (last, first, middle initial)').fill('TRAINING, SAMPLE');
  await intake.getByLabel('Permanent duty station').fill('Okinawa');
  await intake.getByLabel('Who is the claim for?').selectOption('both');
  await intake.getByRole('button', { name: 'Review changes' }).click();
  await intake.getByRole('button', { name: 'Apply changes' }).click();
  await packageSection(workspace, 'Documents');
  await workspace.getByRole('button', { name: 'Edit form', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Okinawa overseas COLA', exact: true });
  await editor.getByLabel('Arrival date', { exact: true }).fill('2026 11 05');
  await editor.getByRole('button', { name: 'Save changes' }).click();
  await expect(editor.getByText('Saved to package', { exact: true })).toBeVisible();
  await editor.getByRole('button', { name: 'Back to package' }).click();
  await workspace.getByRole('button', { name: 'Sign official form' }).click();
  const signing = page.getByRole('region', { name: 'Official form signatures' });
  await signing.getByRole('button', { name: 'Review signature location' }).click();
  const location = signing.getByLabel('PDF signature location');
  await location.selectOption({ label: 'Member signature' });
  await signing.getByRole('button', { name: 'Fill Dependent name (row 2)', exact: true }).click();
  const name = page.getByRole('textbox', { name: 'Dependent name (row 2)', exact: true });
  await expect(name).toBeFocused();
  await name.fill('TRAINING, DEPENDENT');
  await page.getByLabel('Relationship (row 2)', { exact: true }).fill('Child');
  await page.getByLabel('Date of birth (row 2)', { exact: true }).fill('2015 01 01');
  await page.getByRole('button', { name: 'Back to signing' }).click();
  await expect(location).toHaveValue(/SigMem\[0\]$/);
  await expect(signing.getByRole('button', { name: /Fill Dependent/ })).toHaveCount(0);
});
