async function bytes(download: Download) {
  const path = await download.path(); if (!path) throw new Error('The review file was not downloaded.'); return readFile(path);
}
async function savedPackage(page: Page, id: string) {
  return page.evaluate(async key => new Promise<{ revisions: Array<{ id: string }>; reviewApplications?: Array<{ returnId: string; revisionId: string }> }>((resolve, reject) => {
    const open = indexedDB.open('dondocs'); open.onerror = () => reject(open.error); open.onsuccess = () => {
      const db = open.result, request = db.transaction('app', 'readonly').objectStore('app').get(`action-package:${key}`);
      request.onsuccess = () => { resolve(request.result.value); db.close(); }; request.onerror = () => { reject(request.error); db.close(); };
    };
  }), id);
}
