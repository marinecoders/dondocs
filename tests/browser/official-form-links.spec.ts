import { expect, test } from '@playwright/test';
import { choosePackage, newBlankPackage, openPackageWorkspace, packageSection } from './_helpers/packageWorkspace';

test.use({ serviceWorkers: 'block' });
test.setTimeout(120_000);

test('shares a Marine identity with selected forms and reviews subsequent local conflicts', async ({ page, context }) => {
  await context.addInitScript(() => localStorage.setItem('browser-test-visitor', 'returning'));
  await page.goto('/');
  const workspace = await openPackageWorkspace(page);
  await newBlankPackage(workspace, 'Identity sharing');
  await packageSection(workspace, 'Documents');
  for (const [index, label] of ['Page 11', 'Unit Punishment Book', 'Unit Punishment Book'].entries()) {
    await workspace.getByRole('button', { name: 'Add ' + label, exact: true }).click();
    await expect(workspace.locator('li[id^="package-member-"]')).toHaveCount(index + 1);
  }
  await packageSection(workspace, 'Overview');
  const details = workspace.getByRole('region', { name: 'Details', exact: true });
  await details.getByText('Share Marine details across forms', { exact: true }).click();
  await details.getByLabel('1. Page 11', { exact: true }).check();
  await details.getByLabel('2. Unit Punishment Book', { exact: true }).check();
  await details.getByRole('button', { name: 'Link selected forms' }).click();
  const name = details.getByRole('textbox', { name: /Marine name \(last/ });
  await name.fill('De La Cruz, Ana Maria, Jo');
  await details.getByLabel('Official form shared value').selectOption('new:edipi');
  await details.getByRole('button', { name: 'Link selected forms' }).click();
  const edipi = details.getByRole('textbox', { name: 'Marine EDIPI', exact: true });
  await edipi.fill('1234');
  const review = details.getByRole('button', { name: 'Review changes', exact: true });
  const changes = details.getByRole('region', { name: 'Package changes preview' });
  await review.click();
  await expect(changes).toContainText('Enter a ten-digit EDIPI');
  await expect(changes.getByRole('button', { name: 'Apply package changes' })).toBeDisabled();
  await edipi.fill('0012345678');
  await review.click();
  await expect(changes).toContainText('Package value: De La Cruz, Ana Maria Jo');
  await expect(changes).toContainText('2. Unit Punishment Book');
  await expect(changes.locator('article')).toHaveCount(6);
  const apply = changes.getByRole('button', { name: 'Apply package changes' });
  await apply.click();
  await expect(details.getByText('Package changes saved as a new revision.')).toBeVisible();
  await page.reload();
  await openPackageWorkspace(page);
  await choosePackage(workspace, 'Identity sharing');
  await packageSection(workspace, 'Documents');
  await workspace.getByRole('button', { name: 'Edit form', exact: true }).click();
  const editor = page.getByRole('dialog', { name: 'Identity sharing', exact: true });
  const picker = editor.getByRole('combobox', { name: 'Package document' });
  await picker.selectOption({ label: '1. Page 11' });
  await expect(editor.getByLabel('Last Name', { exact: true })).toHaveValue('De La Cruz');
  await expect(editor.getByLabel('First Name', { exact: true })).toHaveValue('Ana Maria');
  await expect(editor.getByLabel('Middle Name', { exact: true })).toHaveValue('Jo');
  await expect(editor.getByLabel('EDIPI', { exact: true })).toHaveValue('0012345678');
  await picker.selectOption({ label: '3. Unit Punishment Book' });
  const accused = editor.getByLabel('18 Accused full name', { exact: true });
  await expect(accused).toHaveValue('');
  await picker.selectOption({ label: '2. Unit Punishment Book' });
  await expect(accused).toHaveValue('De La Cruz, Ana Maria Jo');
  await expect(editor.getByLabel('20 Accused EDIPI', { exact: true })).toHaveValue('0012345678');
  await expect(editor.locator('#pkg-answer-8b_njp_authority_edipi')).toHaveValue('');
  await accused.fill('Local spelling');
  await expect(editor.getByText(/Shared values: Marine name/)).toBeVisible();
  await editor.getByRole('button', { name: 'Open shared package details' }).click();
  await details.getByRole('button', { name: 'Edit details' }).click();
  await name.fill('De La Cruz, Ana Maria');
  await review.click();
  const conflict = changes.locator('article').filter({ hasText: 'Local spelling' });
  await expect(conflict).toContainText('edited independently');
  await expect(apply).toBeDisabled();
  await conflict.getByRole('combobox').selectOption('keep-local');
  await review.click();
  await apply.click();
  await expect(details.getByText('Package changes saved as a new revision.')).toBeVisible();
  await packageSection(workspace, 'Documents');
  await workspace.getByRole('button', { name: 'Edit form', exact: true }).click();
  await picker.selectOption({ label: '2. Unit Punishment Book' });
  await expect(accused).toHaveValue('Local spelling');
  await picker.selectOption({ label: '1. Page 11' });
  await expect(editor.getByLabel('Middle Name', { exact: true })).toHaveValue('');
});
