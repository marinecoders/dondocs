import JSZip from 'jszip';
import { bodyTableSchema, bodyTableTwips, type BodyTable } from '@/lib/bodyTable';

/** Pandoc emits a leading raw marker as its own cell paragraph. Keep its
 * bookmark and first-paragraph style without adding a visible blank line. */
function joinMarkerParagraph(cell: string, index: number): string {
  return cell.replace(/(<w:p\b[^>]*>)([\s\S]*?)<\/w:p>\s*<w:p\b[^>]*>([\s\S]*?)<\/w:p>/, (original, opening: string, first: string, second: string) => {
    const withoutProperties = first.replace(/<w:pPr\b[^>]*>[\s\S]*?<\/w:pPr>|<w:pPr\s*\/>/g, '').trim();
    if (!/^<w:bookmarkStart\b[^>]*\/>\s*<w:bookmarkEnd\b[^>]*\/>$/.test(withoutProperties)
      || !withoutProperties.includes(`w:name="DonDocsBodyTable${index}"`)) return original;
    const content = second.replace(/<w:pPr\b[^>]*>[\s\S]*?<\/w:pPr>|<w:pPr\s*\/>/g, '');
    return `${opening}${first}${content}</w:p>`;
  });
}

/** Markers are generated by the flat-source writer, never matched by cell text. */
export function applyBodyTableLayouts(xml: string, tables: readonly BodyTable[], textWidth = 9360): string {
  const seen = new Set<number>();
  const output = xml.replace(/<w:tbl\b[^>]*>[\s\S]*?<\/w:tbl>/g, original => {
    const markers = [...original.matchAll(/w:name="DonDocsBodyTable(\d+)"/g)];
    if (!markers.length) return original;
    if (markers.length !== 1) throw new Error('A Word table has ambiguous layout markers.');
    const index = Number(markers[0][1]), input = tables[index];
    if (!input || seen.has(index)) throw new Error('The Word table layout does not match its captured source.');
    seen.add(index);
    const table = bodyTableSchema.parse(input), widths = bodyTableTwips(table, textWidth);
    const borders = table.borders ?? 'grid';
    const borderXml = `<w:tblBorders>${['top', 'left', 'bottom', 'right', 'insideH', 'insideV'].map(side =>
      `<w:${side} w:val="${borders === 'none' || borders === 'outline' && side.startsWith('inside') ? 'nil' : 'single'}" w:sz="4" w:color="000000"/>`).join('')}</w:tblBorders>`;
    let result = original.replace(/<w:tblPr>[\s\S]*?<\/w:tblPr>/, `<w:tblPr><w:tblW w:w="${textWidth}" w:type="dxa"/>${borderXml}<w:tblLayout w:type="fixed"/><w:tblCellMar><w:top w:w="40" w:type="dxa"/><w:left w:w="60" w:type="dxa"/><w:bottom w:w="40" w:type="dxa"/><w:right w:w="60" w:type="dxa"/></w:tblCellMar></w:tblPr>`);
    result = result.replace(/<w:tblGrid>[\s\S]*?<\/w:tblGrid>/, `<w:tblGrid>${widths.map(width => `<w:gridCol w:w="${width}"/>`).join('')}</w:tblGrid>`);
    let row = 0;
    result = result.replace(/<w:tr\b[^>]*>[\s\S]*?<\/w:tr>/g, tr => {
      const current = row++;
      let cell = 0;
      const properties = `<w:trPr>${table.minimumRowHeight ? `<w:trHeight w:val="${Math.round(table.minimumRowHeight * 20)}" w:hRule="atLeast"/>` : ''}${current < table.headerRows && table.repeatHeaders !== false ? '<w:tblHeader/>' : ''}</w:trPr>`;
      const cells = tr.replace(/<w:trPr>[\s\S]*?<\/w:trPr>|<w:trPr\s*\/>/g, '').replace(/<w:tc\b[^>]*>[\s\S]*?<\/w:tc>/g, tc => {
        const column = cell++;
        if (column >= widths.length) throw new Error('The Word table contains unexpected columns.');
        let content = joinMarkerParagraph(tc.replace(/<w:tcPr>[\s\S]*?<\/w:tcPr>|<w:tcPr\s*\/>/g, ''), index);
        content = content.replace(/<w:p\b[^>]*>[\s\S]*?<\/w:p>/g, p => {
          p = p.replace(/<w:pPr\s*\/>/g, '');
          const alignment = `<w:jc w:val="${table.columnAlignments?.[column] ?? 'left'}"/>`;
          let paragraph = p.replace(/<w:jc\b[^>]*\/>|<w:keepNext\b[^>]*\/>|<w:wordWrap\b[^>]*\/>/g, '');
          if (paragraph.includes('<w:pPr>')) paragraph = paragraph.replace(/<w:pPr>([\s\S]*?)<\/w:pPr>/, (_, properties: string) => {
            const wrapTail = /<w:(?:overflowPunct|topLinePunct|autoSpaceDE|autoSpaceDN|bidi|adjustRightInd|snapToGrid|spacing|ind|contextualSpacing|mirrorIndents|suppressOverlap|textDirection|textAlignment|textboxTightWrap|outlineLvl|divId|cnfStyle|rPr|sectPr|pPrChange)\b/;
            let next = wrapTail.test(properties) ? properties.replace(wrapTail, '<w:wordWrap w:val="0"/>$&') : properties + '<w:wordWrap w:val="0"/>';
            const alignTail = /<w:(?:textDirection|textAlignment|textboxTightWrap|outlineLvl|divId|cnfStyle|rPr|sectPr|pPrChange)\b/;
            next = alignTail.test(next) ? next.replace(alignTail, alignment + '$&') : next + alignment;
            return `<w:pPr>${next}</w:pPr>`;
          });
          else paragraph = paragraph.replace(/(<w:p\b[^>]*>)/, `$1<w:pPr><w:wordWrap w:val="0"/>${alignment}</w:pPr>`);
          if (table.fontSize) paragraph = paragraph.replace(/<w:r\b[^>]*>[\s\S]*?<\/w:r>/g, run => {
            const size = `<w:sz w:val="${table.fontSize! * 2}"/><w:szCs w:val="${table.fontSize! * 2}"/>`;
            const cleaned = run.replace(/<w:rPr\s*\/>/g, '').replace(/<w:sz(?:Cs)?\b[^>]*\/>/g, '');
            return cleaned.includes('<w:rPr>') ? cleaned.replace(/<w:rPr>([\s\S]*?)<\/w:rPr>/, (_, properties: string) => {
              const tail = /<w:(?:highlight|u|effect|bdr|shd|fitText|vertAlign|rtl|cs|em|lang|eastAsianLayout|specVanish|oMath|rPrChange)\b/;
              return `<w:rPr>${tail.test(properties) ? properties.replace(tail, size + '$&') : properties + size}</w:rPr>`;
            }) : cleaned.replace(/(<w:r\b[^>]*>)/, `$1<w:rPr>${size}</w:rPr>`);
          });
          return paragraph;
        });
        return content.replace(/(<w:tc\b[^>]*>)/, `$1<w:tcPr><w:tcW w:w="${widths[column]}" w:type="dxa"/><w:vAlign w:val="top"/></w:tcPr>`);
      });
      if (cell !== widths.length) throw new Error('The Word table is missing a captured column.');
      return cells.replace(/(<w:tr\b[^>]*>)/, `$1${properties}`);
    });
    if (row !== table.rows.length) throw new Error('The Word table row count changed during conversion.');
    return result;
  });
  if (seen.size !== tables.length) throw new Error('A captured body table is missing from Word output.');
  return output;
}

/** The companion uses the same table layout pass as the browser converter. */
export async function formatBodyTables(bytes: Uint8Array, tables: readonly BodyTable[]): Promise<Uint8Array> {
  if (!tables.length) return bytes;
  const zip = await JSZip.loadAsync(bytes);
  const entry = zip.file('word/document.xml');
  if (!entry) throw new Error('Word output is missing its document part.');
  zip.file('word/document.xml', applyBodyTableLayouts(await entry.async('string'), tables));
  return zip.generateAsync({ type: 'uint8array', compression: 'DEFLATE' });
}
